CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE, name VARCHAR(80) NOT NULL DEFAULT '',
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'member', mfa_secret VARCHAR(64) NULL,
 blocked TINYINT NOT NULL DEFAULT 0, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content (
 id VARCHAR(100) PRIMARY KEY, kind VARCHAR(20) NOT NULL, payload JSON NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'draft', version INT NOT NULL DEFAULT 1,
 reviewer CHAR(36) NULL, author CHAR(36) NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX ix_content(kind,state)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS attempts (
 id CHAR(36) PRIMARY KEY, owner VARCHAR(80) NOT NULL, scenario VARCHAR(80) NOT NULL,
 snapshot JSON NOT NULL, current_scene VARCHAR(30) NOT NULL, choices JSON NOT NULL,
 finished TINYINT NOT NULL DEFAULT 0, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX ix_owner(owner,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS question_attempts (
 id CHAR(36) PRIMARY KEY, owner VARCHAR(80) NOT NULL, question_id VARCHAR(100) NOT NULL,
 topic VARCHAR(60) NOT NULL, answer VARCHAR(20) NOT NULL, correct TINYINT NOT NULL,
 explanation TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX ix_questions_owner(owner,question_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS lesson_progress (
 owner VARCHAR(80) NOT NULL, slug VARCHAR(80) NOT NULL, step INT NOT NULL DEFAULT 0,
 completed TINYINT NOT NULL DEFAULT 0, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(owner,slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS promises (
 id CHAR(36) PRIMARY KEY, owner VARCHAR(80) NOT NULL, day DATE NOT NULL,
 lesson VARCHAR(80) NOT NULL, title TEXT NOT NULL, state VARCHAR(20) NOT NULL DEFAULT 'selected',
 UNIQUE KEY ux_promise(owner,day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS preferences (
 owner VARCHAR(80) PRIMARY KEY, payload JSON NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS idempotency_keys (
 owner VARCHAR(80) NOT NULL, event_key VARCHAR(80) NOT NULL, request_hash CHAR(64) NOT NULL,
 response JSON NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(owner,event_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS feedback (
 id CHAR(36) PRIMARY KEY, owner VARCHAR(80) NOT NULL, category VARCHAR(30) NOT NULL,
 message TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket CHAR(64) NOT NULL, window_start BIGINT NOT NULL, hits INT NOT NULL DEFAULT 1,
 PRIMARY KEY(bucket,window_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor CHAR(36) NOT NULL,
 action VARCHAR(60) NOT NULL, object_id VARCHAR(100) NOT NULL, detail JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, content_id VARCHAR(100) NOT NULL,
 actor CHAR(36) NOT NULL, payload JSON NOT NULL, version INT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS daily_bundles (
 day DATE PRIMARY KEY, scenario VARCHAR(80) NOT NULL, lesson VARCHAR(80) NOT NULL,
 question_id VARCHAR(80) NOT NULL, theme VARCHAR(220) NULL, tip TEXT NULL, promise TEXT NULL,
 version INT NOT NULL DEFAULT 1, state VARCHAR(20) NOT NULL DEFAULT 'draft',
 reviewer CHAR(36) NULL, author CHAR(36) NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS password_resets (
 token_hash CHAR(64) PRIMARY KEY, user_id CHAR(36) NOT NULL, expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
